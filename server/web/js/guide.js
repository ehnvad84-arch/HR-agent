/** Таблица для показа: columns — четыре роли, rows — {title, cells: [{yes, text}]} в порядке ролей. */
export function rightsTable() {
  return {
    columns: GUIDE_ROLES.map((role) => ({ role, title: ROLE_TITLES[role] })),
    rows: RIGHTS.map((right) => ({
      title: right.title, perm: right.perm,
      cells: GUIDE_ROLES.map((role) => {
        const yes = ROLE_PERMS[role].includes(right.perm);
        return { yes, text: yes ? (right.yes && right.yes[role]) || "да" : (right.no && right.no[role]) || "нет" };
      }),
    })),
  };
}

/** «Что доступно вам»: фразы по тем правам, которые пришли в /api/me.permissions (can — session.can). */
export function myRights(can) {
  return RIGHTS.filter((right) => can(right.perm)).map((right) => right.mine);
}

