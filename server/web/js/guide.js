export const guideKey = (user) => `hrGuideSeen:${user && user.id !== undefined ? user.id : "anon"}`;

/** Блок открыт, пока человек не видел справку (первый вход на этом компьютере); хранилище закрыто — не навязываем. */
export function guideOpen(storage, user) {
  try {
    return storage ? storage.getItem(guideKey(user)) === null : false;
  } catch {
    return false;
  }
}

export function markGuideSeen(storage, user) {
  try {
    if (storage) storage.setItem(guideKey(user), "1");
  } catch { /* хранилище закрыто: справка просто останется свёрнутой */ }
}
