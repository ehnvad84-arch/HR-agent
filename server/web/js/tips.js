const norm = (text) => (text || "").replace(/\s+/g, " ").trim();

/** Текст подсказки для элемента или "" — если подсказки нет. */
export function tipFor(el) {
  if (!el) return "";
  const own = el.getAttribute("data-tip");
  if (own) return TIPS[own] || own;
  const label = norm(el.getAttribute("aria-label")) || norm(el.textContent);
  if (TIPS[label]) return TIPS[label];
  const cut = label.replace(/\s+\d+$/, "");   // «Сегодня 8» — вкладка с бейджем
  return TIPS[cut] || "";
}
